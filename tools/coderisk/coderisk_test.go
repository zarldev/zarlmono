func TestAnalyzeWeightedCoverage(t *testing.T) {
	t.Parallel()
	root, inventory := fixture(t, map[string]string{"sample.go": `package sample
func Score(x int) int {
 if x > 0 { x++; x++; x++ }
 return x
}
`})
	for _, tc := range []struct {
		name     string
		counts   string
		coverage float64
		risk     float64
	}{
		{name: "uncovered", counts: "0 0 0", coverage: 0, risk: 6},
		{name: "partial weighted", counts: "1 0 1", coverage: 40, risk: 2.864},
		{name: "covered", counts: "1 1 1", coverage: 100, risk: 2},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			counts := strings.Fields(tc.counts)
			profile := fmt.Sprintf("mode: atomic\nexample.test/sample/sample.go:2.23,3.11 1 %s\nexample.test/sample/sample.go:3.11,3.28 3 %s\nexample.test/sample/sample.go:4.2,4.10 1 %s\n", counts[0], counts[1], counts[2])
			functions := analyze(t, root, inventory, profile)
			if len(functions) != 1 {
				t.Fatalf("got %d functions, want 1", len(functions))
			}
			fn := functions[0]
			if fn.Complexity != 2 || fn.Statements != 5 || fn.File != "sample.go" || fn.Line != 2 {
				t.Fatalf("unexpected function: %+v", fn)
			}
			checkMetric(t, "coverage", fn.Coverage, tc.coverage)
			checkMetric(t, "CRAP", fn.CRAP, tc.risk)
		})
	}
}

func TestAnalyzeUnknownAndExclusions(t *testing.T) {
	t.Parallel()
	root, inventory := fixture(t, map[string]string{
		"sample.go":      "package sample\nfunc Empty() {}\nfunc Missing() { println(1) }\nfunc External()\nvar Callback = func() { println(1) }\n",
		"generated.go":   "// Code generated by fixture. DO NOT EDIT.\npackage sample\nfunc Generated() { println(1) }\n",
		"sample_test.go": "package sample_test\nfunc TestExcluded() {}\n",
	})
	// Empty has an instrumented zero-statement block; Missing has no data.
	functions := analyze(t, root, inventory, "mode: set\nexample.test/sample/sample.go:2.14,2.16 0 1\n")
	if len(functions) != 2 {
		t.Fatalf("got %d functions, want Empty and Missing", len(functions))
	}
	for _, fn := range functions {
		if fn.Coverage != nil || fn.CRAP != nil {
			t.Errorf("%s: unmeasured metrics must be nil: %+v", fn.Name, fn)
		}
	}
}

func TestAnalyzeSameLineMethodsAndClosures(t *testing.T) {
	t.Parallel()
	source := `package sample
type Box[T any] struct{}
func (b *Box[T]) First() { if true { println(1) } }; func (b Box[T]) Second() { func() { if true && false { println(2) } }() }
`
	root, inventory := fixture(t, map[string]string{"sample.go": source})
	line := strings.Split(source, "\n")[2]
	first := strings.Index(line, "if true") + 1
	second := strings.Index(line, "func()") + 1
	profile := fmt.Sprintf("mode: count\nexample.test/sample/sample.go:3.%d,3.%d 2 0\nexample.test/sample/sample.go:3.%d,3.%d 3 1\n", first, first+10, second, second+10)
	functions := analyze(t, root, inventory, profile)
	if len(functions) != 2 {
		t.Fatalf("got %d functions, want 2", len(functions))
	}
	if fn := functions[0]; fn.Name != "(*Box[T]).First" || fn.Complexity != 2 || fn.Statements != 2 || fn.Covered != 0 {
		t.Errorf("first method: %+v", fn)
	}
	if fn := functions[1]; fn.Name != "(Box[T]).Second" || fn.Complexity != 3 || fn.Statements != 3 || fn.Covered != 3 {
		t.Errorf("second method with closure: %+v", fn)
	}
}

func TestAnalyzeDecisionCounting(t *testing.T) {
	t.Parallel()
	root, inventory := fixture(t, map[string]string{"sample.go": `package sample
func Decisions(x int, ch chan int) {
 for i := 0; i < x; i++ { if i > 0 && i < 2 || i == 5 { continue } }
 for range []int{1} {}
 switch x { case 1, 2: println(1); case 3: println(3); default: }
 select { case <-ch: default: }
}
`})
	functions := analyze(t, root, inventory, "mode: set\n")
	// Base + for + if + && + || + range + two cases + one select case.
	if got := functions[0].Complexity; got != 9 {
		t.Fatalf("complexity = %d, want 9", got)
	}
}

func TestAnalyzeRejectsInvalidInputs(t *testing.T) {
	t.Parallel()
	root, inventory := fixture(t, map[string]string{"sample.go": "package sample\nfunc F() {}\n"})
	for _, profile := range []string{"", "mode: invalid\n", "mode: set\nbroken\n"} {
		if _, err := coderisk.Analyze(root, bytes.NewReader(inventory), strings.NewReader(profile)); err == nil {
			t.Errorf("accepted invalid profile %q", profile)
		}
	}
	for _, inventory := range []string{"", "{}"} {
		if _, err := coderisk.Analyze(root, strings.NewReader(inventory), strings.NewReader("mode: set\n")); err == nil {
			t.Errorf("accepted empty inventory %q", inventory)
		}
	}
	_, err := coderisk.Analyze(root, strings.NewReader("!"), strings.NewReader("mode: set\n"))
	var syntax *json.SyntaxError
	if !errors.As(err, &syntax) {
		t.Fatalf("invalid inventory error = %v, want JSON syntax error", err)
	}
	writeFile(t, root, "sample.go", "not Go")
	_, err = coderisk.Analyze(root, bytes.NewReader(inventory), strings.NewReader("mode: set\n"))
	var sourceSyntax scanner.ErrorList
	if !errors.As(err, &sourceSyntax) {
		t.Fatalf("invalid source error = %v, want Go syntax error", err)
	}
}

func TestRankAndReports(t *testing.T) {
	t.Parallel()
	root, inventory := fixture(t, map[string]string{
		"sample.go": "package sample\nfunc B() { println(1) }; func A() { println(1) }\nfunc Unknown() { if true {} }\n",
	})
	functions := analyze(t, root, inventory, "mode: set\nexample.test/sample/sample.go:2.10,2.24 1 0\nexample.test/sample/sample.go:2.35,2.49 1 0\n")
	functions[0], functions[2] = functions[2], functions[0]
	coderisk.Rank(functions)
	if functions[0].Name != "B" || functions[1].Name != "A" || functions[2].Name != "Unknown" {
		t.Fatalf("rank not deterministic by risk/location: %+v", functions)
	}
	report := coderisk.Report{Modules: []string{"fixture"}, Functions: functions}
	markdown := report.Markdown(1)
	for _, text := range []string{"2 measured", "1 unmeasured", "| `B`", "| `Unknown`", "0.0% | 2.00", "Report only", "statement-weighted"} {
		if !strings.Contains(markdown, text) {
			t.Errorf("Markdown missing %q: %s", text, markdown)
		}
	}
	if strings.Contains(markdown, "| `A`") {
		t.Error("Markdown ignored top limit")
	}
	if !strings.Contains(report.Markdown(0), "| `A`") {
		t.Error("unlimited Markdown omitted a function")
	}
	encoded, err := json.Marshal(report)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(encoded, []byte(`"crap":null`)) || !bytes.Contains(encoded, []byte(`"coverage_percent":null`)) {
		t.Fatalf("JSON must preserve unknown metrics: %s", encoded)
	}
}

func TestAnalyzeRealGoCoverage(t *testing.T) {
	t.Parallel()
	root, _ := fixture(t, map[string]string{
		"sample.go":      "package sample\nfunc Value(x bool) int { if x { return 1 }; return 2 }\nfunc Untested() int { return 3 }\n",
		"generated.go":   "// Code generated by fixture. DO NOT EDIT.\npackage sample\nfunc Generated() {}\n",
		"inactive.go":    "//go:build coderisk_unused_tag\n\npackage sample\nfunc Inactive() {}\n",
		"sample_test.go": "package sample_test\nimport (\"testing\"; sample \"example.test/sample\")\nfunc TestValue(t *testing.T) { if sample.Value(true) != 1 { t.Fatal(\"value\") } }\n",
	})
	writeFile(t, root, "go.mod", "module example.test/sample\n\ngo 1.27.0\n")
	goCommand := func(args ...string) []byte {
		t.Helper()
		cmd := exec.CommandContext(t.Context(), "go", args...)
		cmd.Dir = root
		cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=")
		output, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("go %v: %v\n%s", args, err, output)
		}
		return output
	}
	goCommand("test", "-coverprofile=coverage.out", "./...")
	inventory := goCommand("list", "-json", "./...")
	profile, err := os.ReadFile(filepath.Join(root, "coverage.out"))
	if err != nil {
		t.Fatal(err)
	}
	functions := analyze(t, root, inventory, string(profile))
	if len(functions) != 2 {
		t.Fatalf("got %d functions, want only Value and Untested", len(functions))
	}
	checkMetric(t, "Value coverage", functions[0].Coverage, 200.0/3)
	checkMetric(t, "Untested coverage", functions[1].Coverage, 0)
	checkMetric(t, "Untested CRAP", functions[1].CRAP, 2)
}

func fixture(t *testing.T, sources map[string]string) (string, []byte) {
	t.Helper()
	root := t.TempDir()
	files := make([]string, 0, len(sources))
	for name, source := range sources {
		writeFile(t, root, name, source)
		files = append(files, name)
	}
	inventory, err := json.Marshal(map[string]any{"Dir": root, "ImportPath": "example.test/sample", "GoFiles": files})
	if err != nil {
		t.Fatal(err)
	}
	return root, inventory
}

func analyze(t *testing.T, root string, inventory []byte, profile string) []coderisk.Function {
	t.Helper()
	functions, err := coderisk.Analyze(root, bytes.NewReader(inventory), strings.NewReader(profile))
	if err != nil {
		t.Fatal(err)
	}
	return functions
}

func checkMetric(t *testing.T, name string, got *float64, want float64) {
	t.Helper()
	if got == nil {
		t.Fatalf("%s is unknown, want %g", name, want)
	}
	if math.Abs(*got-want) > 1e-9 {
		t.Errorf("%s = %g, want %g", name, *got, want)
	}
}

func writeFile(t *testing.T, root, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(root, name), []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}
